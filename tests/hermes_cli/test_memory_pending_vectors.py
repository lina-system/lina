"""lina#644: search over migrated memory says it is partial while conclusions wait for their vectors.

These run on the real Postgres from tests/_fixtures/memory_store.py, with a store holding Honcho conclusions
(``ltm.documents``) that have no vector of the configured model, as `lina migrate memory` leaves them.
"""

from __future__ import annotations

import json

import pytest

from agent.embedding_client import DEFAULT_MODEL
from plugins.memory.honcho import HonchoMemoryProvider
from plugins.memory.honcho.client import HonchoClientConfig
from plugins.memory.honcho.pending_vectors import pending_counts

PARTIAL = "2 conclusions are not embedded yet; search is partial"


@pytest.fixture
def conclusions(memory_store_sql):
    """Workspace ``hermes``: one embedded conclusion, two pending (one has only another model's vector), a deleted
    and an empty one that reembed never embeds. Workspace ``other``: one pending."""
    memory_store_sql("CREATE TABLE ltm.documents (id text PRIMARY KEY, vec_id bigint GENERATED BY DEFAULT AS "
                     "IDENTITY UNIQUE, workspace_name text NOT NULL, content text, deleted_at timestamptz)")
    memory_store_sql("INSERT INTO ltm.documents (id, workspace_name, content, deleted_at) VALUES "
                     "('d1', 'hermes', 'embedded', NULL), ('d2', 'hermes', 'the owner prefers green tea', NULL), "
                     "('d3', 'hermes', 'an old model only', NULL), ('d4', 'hermes', 'deleted', now()), "
                     "('d5', 'hermes', '  ', NULL), ('o1', 'other', 'another agent', NULL)")
    _embed(memory_store_sql, "d1", DEFAULT_MODEL)
    _embed(memory_store_sql, "d3", "an-older-model")
    yield memory_store_sql
    memory_store_sql("DROP TABLE ltm.documents")


def _embed(sql, document: str, model: str) -> None:
    sql("INSERT INTO vec.embeddings (kind, item_id, agent_id, model, dim, embedding) "
        "SELECT 'document', vec_id, workspace_name, %s, 1024, array_fill(0.03125::real, ARRAY[1024])::vector "
        "FROM ltm.documents WHERE id = %s", (model, document))


class _Backend:
    def search_context(self, session_key, query, max_tokens=800, peer="user"):
        return ""

    def dialectic_query(self, session, prompt, **kwargs):
        return ""


def _provider(*, recall_sync: bool = True, base_url: str = "http://127.0.0.1:8000") -> HonchoMemoryProvider:
    provider = HonchoMemoryProvider(card_in_prompt=True)
    cfg = HonchoClientConfig(timeout=1, base_url=base_url, workspace_id="hermes")
    cfg.recall_sync = recall_sync
    provider._config = cfg
    provider._manager = _Backend()
    provider._session_key = "session-a"
    provider._session_initialized = True
    for name in ("recall_sync", "recall_mode", "injection_frequency", "context_cadence",
                 "dialectic_cadence", "dialectic_depth", "dialectic_depth_levels"):
        setattr(provider, f"_{name}", getattr(cfg, name))
    return provider


def test_pending_counts_are_per_workspace_and_skip_what_reembed_never_embeds(conclusions):
    assert pending_counts(DEFAULT_MODEL) == {"hermes": 2, "other": 1}
    assert pending_counts(DEFAULT_MODEL, "hermes") == {"hermes": 2}


def test_honcho_search_says_search_is_partial_instead_of_a_bare_empty_answer(conclusions):
    out = json.loads(_provider().handle_tool_call("honcho_search", {"query": "what tea does the owner like"}))
    assert out["result"] == "No relevant context found."
    assert out["partial"].startswith(PARTIAL)


def test_search_is_not_partial_once_every_conclusion_has_a_vector(conclusions):
    for document in ("d2", "d3"):
        _embed(conclusions, document, DEFAULT_MODEL)
    out = json.loads(_provider().handle_tool_call("honcho_search", {"query": "what tea does the owner like"}))
    assert "partial" not in out


def test_a_honcho_outside_this_machine_is_not_counted_against_the_local_store(conclusions):
    out = json.loads(_provider(base_url="https://api.honcho.dev").handle_tool_call(
        "honcho_search", {"query": "what tea does the owner like"}))
    assert "partial" not in out


@pytest.mark.parametrize("recall_sync", [True, False])
def test_recall_prefetch_says_search_is_partial(conclusions, recall_sync):
    provider = _provider(recall_sync=recall_sync)
    provider._recall_waited_turn = provider._turn_count  # the turn-start waits already ran
    assert PARTIAL in provider.prefetch("what tea does the owner like")


def test_explicit_recall_says_search_is_partial(conclusions):
    assert PARTIAL in _provider().recall_query("what tea does the owner like")


def test_doctor_lists_pending_vectors_per_workspace(conclusions, tmp_path, monkeypatch, capsys):
    from hermes_cli import store
    from hermes_cli.doctor_state import _check_memory_vectors
    (tmp_path / "store.env").write_text("LINA_STORE_PASSWORD=placeholder\n", encoding="utf-8")
    monkeypatch.setattr(store, "store_dir", lambda: tmp_path)

    finding = _check_memory_vectors(False)

    out = capsys.readouterr().out
    assert f"Honcho workspace hermes: 2 conclusion(s) without a {DEFAULT_MODEL} vector" in out
    assert f"Honcho workspace other: 1 conclusion(s) without a {DEFAULT_MODEL} vector" in out
    assert any("lina store reembed --source memory" in issue for issue in finding.manual_issues)


def test_doctor_is_silent_without_a_lina_store(tmp_path, monkeypatch, capsys):
    from hermes_cli import store
    from hermes_cli.doctor_state import _check_memory_vectors
    monkeypatch.setattr(store, "store_dir", lambda: tmp_path)

    finding = _check_memory_vectors(False)

    assert capsys.readouterr().out == ""
    assert finding.manual_issues == []
