// unicodegen converts pinned Unicode data into sorted, compact range tables.
// Usage: go run ./internal/unicodegen <download-directory> > unicode_tables.go
package main

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

type entry struct {
	lo, hi int64
	value  string
}

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: unicodegen <Unicode-17.0.0-data-directory>")
		os.Exit(64)
	}
	var out bytes.Buffer
	fmt.Fprintln(&out, "// SPDX-License-Identifier: Apache-2.0\n\n// Code generated by internal/unicodegen from Unicode 17.0.0 data. DO NOT EDIT.\n// Data copyright Unicode, Inc.; see THIRD-PARTY-NOTICES.md.\n\npackage render")
	inputs := []struct{ name, hash string }{
		{"GraphemeBreakProperty.txt", "d6b51d1d2ae5c33b451b7ed994b48f1f4dc62b2272a5831e7fd418514a6bae89"},
		{"EastAsianWidth.txt", "ea7ce50f3444a050333448dffef1cadd9325af55cbb764b4a2280faf52170a33"},
		{"emoji-data.txt", "2cb2bb9455cda83e8481541ecf5b6dfda66a3bb89efa3fa7c5297eccf607b72b"},
		{"DerivedCoreProperties.txt", "24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08"},
	}
	tables := map[string][]entry{}
	for _, input := range inputs {
		data, err := os.ReadFile(filepath.Join(os.Args[1], input.name))
		must(err)
		if fmt.Sprintf("%x", sha256.Sum256(data)) != input.hash {
			panic("Unicode input digest mismatch: " + input.name)
		}
		scanner := bufio.NewScanner(bytes.NewReader(data))
		for scanner.Scan() {
			raw, _, _ := strings.Cut(scanner.Text(), "#")
			fields := strings.Split(raw, ";")
			if len(fields) < 2 {
				continue
			}
			span := strings.Split(strings.TrimSpace(fields[0]), "..")
			lo, err := strconv.ParseInt(span[0], 16, 32)
			must(err)
			hi := lo
			if len(span) == 2 {
				hi, err = strconv.ParseInt(span[1], 16, 32)
				must(err)
			}
			prop := strings.TrimSpace(fields[1])
			table, value := "", "1"
			switch input.name {
			case "GraphemeBreakProperty.txt":
				if prop == "LV" || prop == "LVT" {
					continue
				} // Algorithmic Hangul syllables.
				table = "graphemeRanges"
				value = "gb" + strings.ReplaceAll(prop, "_", "")
			case "EastAsianWidth.txt":
				if prop == "W" || prop == "F" {
					table = "wideRanges"
				}
			case "emoji-data.txt":
				if prop == "Extended_Pictographic" {
					table = "pictographicRanges"
				}
				if prop == "Emoji_Presentation" {
					table = "emojiPresentationRanges"
				}
				if prop == "Emoji" {
					table = "emojiRanges"
				}
			case "DerivedCoreProperties.txt":
				if prop == "InCB" && len(fields) == 3 {
					table = "indicRanges"
					value = "incb" + strings.TrimSpace(fields[2])
				}
			}
			if table != "" {
				tables[table] = append(tables[table], entry{lo, hi, value})
			}
		}
		must(scanner.Err())
	}
	names := []string{}
	for name := range tables {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		entries := tables[name]
		sort.Slice(entries, func(i, j int) bool { return entries[i].lo < entries[j].lo })
		var compact []entry
		for _, e := range entries {
			n := len(compact)
			if n > 0 && compact[n-1].hi+1 == e.lo && compact[n-1].value == e.value {
				compact[n-1].hi = e.hi
			} else {
				compact = append(compact, e)
			}
		}
		fmt.Fprintf(&out, "\nvar %s = []runeRange{\n", name)
		for _, e := range compact {
			fmt.Fprintf(&out, "{0x%X,0x%X,%s},\n", e.lo, e.hi, e.value)
		}
		fmt.Fprintln(&out, "}")
	}
	result, err := format.Source(out.Bytes())
	must(err)
	_, err = os.Stdout.Write(result)
	must(err)
}
func must(err error) {
	if err != nil {
		panic(err)
	}
}
