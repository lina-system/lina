-- A run's results tied to the to-do and goal that wanted them (lina#527). One row per file the run left in out/:
-- the run, its to-do and goal, the place of the file (repo and commit stay NULL until the forge of lina#448; path is
-- the Desk path for now) and its kind. Every row written at a run's end is a draft; only the owner's explicit action
-- (`lina work artifact final <id>`, the store's `artifacts.finalize`) makes it final. A new table, not a link kind:
-- a link row holds one target, an artifact holds a path and a commit together.
-- The SQLite edition is the same table in hermes_cli/work/schema_sqlite.sql.
SET search_path TO work, public;

CREATE TABLE IF NOT EXISTS artifact (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id TEXT NOT NULL REFERENCES run (id),
    todo_id TEXT REFERENCES todo (id),
    goal_id TEXT REFERENCES goal (id),
    repo TEXT,
    path TEXT NOT NULL,
    commit_sha TEXT,
    kind TEXT NOT NULL DEFAULT 'draft' CHECK (kind IN ('draft', 'final')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    agent_id TEXT NOT NULL REFERENCES actor (id),
    UNIQUE (run_id, path)
);
CREATE INDEX IF NOT EXISTS artifact_todo_id ON artifact (todo_id);
CREATE INDEX IF NOT EXISTS artifact_goal_id ON artifact (goal_id);
CREATE INDEX IF NOT EXISTS artifact_path ON artifact (path);

-- Row-level security and the agent grant as 0004 gives every work table with agent_id.
DO $$
BEGIN
    IF to_regprocedure('public.lina_apply_agent_rls(regclass)') IS NOT NULL THEN
        PERFORM public.lina_apply_agent_rls('work.artifact'::regclass);
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'lina_app') THEN
        GRANT SELECT, INSERT, UPDATE, DELETE ON work.artifact TO lina_app;
        GRANT USAGE, SELECT ON SEQUENCE work.artifact_id_seq TO lina_app;
    END IF;
END $$;
